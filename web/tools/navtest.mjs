// Exercise navigation: arrow turn, right-drag look, double-click fly, walk mode with collisions.
// usage: node tools/navtest.mjs [outdir]
import { chromium } from 'playwright-core';
const [out = '/tmp'] = process.argv.slice(2);
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('http://localhost:5173/?view=pkin&hour=15');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
await page.keyboard.press('KeyH');
const cam = () => page.evaluate(() => { const { camera: c, controls: t, nav } = window.__three; return { pos: c.position.toArray().map((v) => +v.toFixed(1)), tgt: t.target.toArray().map((v) => +v.toFixed(1)), mode: nav.mode }; });
const log = async (s) => console.log(s.padEnd(22), JSON.stringify(await cam()));
await log('start');
await page.keyboard.down('ArrowLeft'); await page.waitForTimeout(700); await page.keyboard.up('ArrowLeft'); await page.waitForTimeout(300);
await log('turn left 0.7s');
await page.screenshot({ path: `${out}/nav_turn.png` });
await page.mouse.move(700, 450); await page.mouse.down({ button: 'right' }); await page.mouse.move(500, 400, { steps: 10 }); await page.mouse.up({ button: 'right' });
await page.waitForTimeout(300);
await log('right-drag');
await page.mouse.dblclick(700, 500); await page.waitForTimeout(2000);
await log('dblclick');
await page.screenshot({ path: `${out}/nav_dbl.png` });
await page.keyboard.down('Shift'); await page.keyboard.down('ArrowRight'); await page.waitForTimeout(800); await page.keyboard.up('ArrowRight'); await page.keyboard.up('Shift');
await log('shift+right orbit');
await page.keyboard.press('KeyG'); await page.waitForTimeout(1800);
await log('walk');
await page.screenshot({ path: `${out}/nav_walk0.png` });
await page.keyboard.down('KeyW'); await page.waitForTimeout(4000); await page.keyboard.up('KeyW');
await log('walk W 4s');
await page.keyboard.down('Shift'); await page.keyboard.down('KeyW'); await page.waitForTimeout(6000); await page.keyboard.up('KeyW'); await page.keyboard.up('Shift');
await log('run W 6s');
await page.screenshot({ path: `${out}/nav_walk1.png` });
await page.keyboard.down('ArrowRight'); await page.waitForTimeout(1000); await page.keyboard.up('ArrowRight');
await page.keyboard.down('ArrowUp'); await page.waitForTimeout(700); await page.keyboard.up('ArrowUp');
await log('walk look');
await page.screenshot({ path: `${out}/nav_walk2.png` });
await page.keyboard.press('KeyG'); await page.waitForTimeout(500);
await log('orbit again');
await page.keyboard.press('Digit5'); await page.waitForTimeout(2000);
await log('place 5');
await page.screenshot({ path: `${out}/nav_place5.png` });
console.log('errors', errs);
await browser.close();
